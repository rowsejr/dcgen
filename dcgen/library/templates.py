"""Template sheets: one CSV per equipment type plus one Excel workbook with a sheet per type,
a units row and a description row. Engineers fill these in (or export from selection software
and map them); `dcgen library import` turns rows into draft records."""
from __future__ import annotations

from pathlib import Path

from .records import TYPES, columns, spec


def fields_markdown() -> str:
    out = ["# Plant library fields\n", "Generated by `dcgen library docs`. `*` = required.\n"]
    for t, d in TYPES.items():
        out.append(f"\n## {t}  ({d['title']})\n\nFile: `{d['file']}.csv` -> catalogue section `{d['section']}`\n")
        out.append("| field | unit | type | description |\n|---|---|---|---|")
        for f in spec(t):
            out.append(f"| {f.name}{'*' if f.required else ''} | {f.unit} | {f.dtype} | {f.desc} |")
    return "\n".join(out) + "\n"


def write_templates(dest: str | Path) -> list[str]:
    import csv

    import openpyxl
    from openpyxl.styles import Alignment, Font, PatternFill
    from openpyxl.worksheet.datavalidation import DataValidation

    dest = Path(dest)
    dest.mkdir(parents=True, exist_ok=True)
    written = []
    wb = openpyxl.Workbook()
    readme = wb.active
    readme.title = "README"
    for i, line in enumerate([
        "dcgen plant library templates",
        "One sheet per equipment type. Row 1 = field names (do not rename). Row 2 = units. Row 3 = description.",
        "Data starts on row 4. Rows starting with '#' are ignored. The EXAMPLE row is ignored on import.",
        "Imports arrive as DRAFT. Approval is an engineer action: dcgen library approve <ids> --checked-by <name>.",
        "Required fields are marked * in row 3. Lists use ';' (e.g. 25;35;40;45).",
        "Always fill source and conditions so the number can be traced back to a document.",
    ], start=1):
        readme.cell(i, 1, line).font = Font(bold=(i == 1))
    readme.column_dimensions["A"].width = 110
    head = PatternFill("solid", fgColor="DCE6F1")
    for t, d in TYPES.items():
        cols = columns(t)
        path = dest / f"{d['file']}.csv"
        with open(path, "w", newline="", encoding="utf-8") as f:
            w = csv.writer(f)
            w.writerow(cols)
            w.writerow([_ex(fl) for fl in spec(t)])
        written.append(str(path))
        ws = wb.create_sheet(d["file"][:31])
        ws.append(cols)
        ws.append(["#units"] + [fl.unit for fl in spec(t)][1:])
        ws.append(["#" + "required fields marked *"] + [("* " if fl.required else "") + fl.desc for fl in spec(t)][1:])
        ws.append([_ex(fl) for fl in spec(t)])
        for c in range(1, len(cols) + 1):
            ws.cell(1, c).font = Font(bold=True)
            ws.cell(1, c).fill = head
            ws.cell(3, c).alignment = Alignment(wrap_text=True, vertical="top")
            ws.column_dimensions[ws.cell(1, c).column_letter].width = max(14, min(34, len(cols[c - 1]) + 4))
        ws.freeze_panes = "B4"
        for i, fl in enumerate(spec(t), start=1):
            if fl.enum:
                dv = DataValidation(type="list", formula1='"' + ",".join(fl.enum) + '"', allow_blank=True)
                ws.add_data_validation(dv)
                dv.add(f"{ws.cell(4, i).column_letter}4:{ws.cell(4, i).column_letter}2000")
    xlsx = dest / "plant_library_template.xlsx"
    wb.save(xlsx)
    written.append(str(xlsx))
    (dest / "FIELDS.md").write_text(fields_markdown())
    written.append(str(dest / "FIELDS.md"))
    return written


def _ex(f):
    if f.example is None:
        return ""
    return f.example if not isinstance(f.example, (list, dict)) else str(f.example)
